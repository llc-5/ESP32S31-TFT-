/* 编译期完整性校验（不要删）：复制漏行会直接编译报错，而不是花屏 */
typedef char img_avatar_size_guard[(sizeof(IMG_AVATAR_PACKED)==IMG_AVATAR_PACKED_BYTES)?1:-1];

/* ---------- 解码 + 写屏（只用驱动公开的 LCD_ShowImage256） ----------
 * 逐块把位打包数据还原成 8 位索引，放进 1920 字节的静态行缓冲，
 * 再整块交给 LCD_ShowImage256 写 GRAM。块高 8 行：只开窗 40 次，
 * RAM 占用小、速度也够。源图 -> 屏上用整数最近邻映射，与驱动的 blit 完全一致。
 */
#define IMG_BLOCK_ROWS  8
static void IMG_Draw(void)
{
    static uint8_t line[IMG_AVATAR_DW * IMG_BLOCK_ROWS];
    uint16_t y0, rows, r, x, sy, sx;
    uint32_t bit;
    const uint8_t *src;
    for (y0 = 0; y0 < IMG_AVATAR_DH; y0 += IMG_BLOCK_ROWS) {
        rows = IMG_AVATAR_DH - y0;
        if (rows > IMG_BLOCK_ROWS) rows = IMG_BLOCK_ROWS;
        for (r = 0; r < rows; r++) {
            sy = (uint16_t)(((uint32_t)(y0 + r) * IMG_AVATAR_H) / IMG_AVATAR_DH);
            src = IMG_AVATAR_PACKED + (uint32_t)sy * IMG_AVATAR_ROW_BYTES;
            for (x = 0; x < IMG_AVATAR_DW; x++) {
                sx  = (uint16_t)(((uint32_t)x * IMG_AVATAR_W) / IMG_AVATAR_DW);
                bit = (uint32_t)sx * IMG_AVATAR_BPP;
                line[(uint32_t)r * IMG_AVATAR_DW + x] =
                    (uint8_t)((src[bit >> 3] >> (8 - IMG_AVATAR_BPP - (bit & 7)))
                             & (IMG_AVATAR_COLORS - 1));
            }
        }
        /* 加括号阻止同名函数式宏展开；main.c 的调用要走解码，这里要走真实驱动 */
        (LCD_ShowImage256)(IMG_AVATAR_X, IMG_AVATAR_Y + y0,
                           IMG_AVATAR_DW, rows, IMG_AVATAR_PALETTE, line);
    }
}

/* 自动适配：把 main.c 里原有的调用接到 IMG_Draw()，因此 main.c 一个字都不用改。
 * 宏放在文件末尾，IMG_Draw 内部又用 (LCD_ShowImage256)(...) 绕过宏，二者互不干扰。
 * 新版 main.c 走 LCD_ShowImage256Fit，旧版走 LCD_ShowImage256，两条都覆盖。 */
#define LCD_ShowImage256Fit(a,b,c,d,e,f,g,h)  IMG_Draw()
#define LCD_ShowImage256(a,b,c,d,e,f)         IMG_Draw()

